def Fundamental_Analysis(result):
  # ==============================================================================
  # 1. GLOBAL SUPPORT: Works for US (BLK) and India (AXISBANK) automatically.
  # 2. STRICT SCORING: No free points. Banks need ROA > 1% to get high scores.
  # 3. TREND VETO: Even if Score is 9/9, we HOLD if the Trend is Down.
  # 4. OUTPUT: Strict JSON for API integration.
  # ==============================================================================

  import os
  import time
  import warnings
  import numpy as np
  import pandas as pd
  import torch
  import torch.nn as nn
  import lightgbm as lgb
  import yfinance as yf
  from sklearn.preprocessing import StandardScaler
  from google.colab import drive

  warnings.filterwarnings('ignore')

  # --- 1. CONFIGURATION & DRIVE ---
