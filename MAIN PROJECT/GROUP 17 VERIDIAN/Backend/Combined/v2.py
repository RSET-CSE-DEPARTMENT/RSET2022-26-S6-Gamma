# --- PART 1: THE TEACHER ---
class VeridianTeacher:
    def __init__(self):
        # We don't need to hardcode students here; we adapt to what is passed in
        self.labels = ["Buy", "Sell", "Hold"]

    def process(self, student_outputs):
        # Extract confidences
        confidences = np.array([s['confidence'] for s in student_outputs])

        # Avoid division by zero if all confidences are 0
        if np.sum(confidences) == 0:
            weights = np.ones(len(confidences)) / len(confidences)
        else:
            weights = confidences / np.sum(confidences)

        final_probs = np.zeros(3)

        # Weighted Average of Predictions
        for i, student in enumerate(student_outputs):
            pred = np.array(student['prediction']) # Expecting [Buy, Sell, Hold]
            # Map predictions to 0=Buy, 1=Sell, 2=Hold if necessary,
            # assuming input is [Buy, Hold, Sell] or [Buy, Sell, Hold]
            # NOTE: Your models output [Buy, Hold, Sell] or [Buy, Sell, Hold].
            # Ensure consistency! I will assume your models output [Buy, Sell, Hold]
            # based on your snippet.

            final_probs += (pred * weights[i])

        # Determine Winner
        winner_idx = np.argmax(weights)
        winning_student = student_outputs[winner_idx]

        # Determine Final Decision
        decision_idx = np.argmax(final_probs)

        return {
            "decision": self.labels[decision_idx],
            "final_probs": final_probs,
            "winner_model": winning_student['model'], # This requires the 'model' key!
            "winner_reason": winning_student['reason'],
            "winner_confidence": winning_student['confidence'],
            "confidence_scores": confidences
        }

