def MacroEconomic_Analysis(ticker):
    import json
    import joblib
    import yfinance as yf
    import pandas as pd
    import numpy as np
    import requests
    from pathlib import Path

    # ----------------------------
    # Paths
    # ----------------------------
    MODEL_DIR = Path("/content/drive/MyDrive/Veridian/Macro")
    MODEL_PATH = MODEL_DIR / "xgb_macro.joblib"
    SCALER_PATH = MODEL_DIR / "scaler.joblib"
    META_PATH = MODEL_DIR / "meta.json"

    # ----------------------------
    # Load artifacts
    # ----------------------------
    model = joblib.load(MODEL_PATH)
    scaler = joblib.load(SCALER_PATH)
    meta = json.load(open(META_PATH))

    FEATURES = meta["features"]

    # ----------------------------
    # World Bank helpers
    # ----------------------------
    WB_INDICATORS = {
        "gdp_growth": "NY.GDP.MKTP.KD.ZG",
        "inflation": "FP.CPI.TOTL.ZG",
        "unemployment": "SL.UEM.TOTL.ZS",
    }

    INDEX_COUNTRY_MAP = {
        "^GSPC": "United States",
        "^DJI": "United States",
        "^IXIC": "United States",
        "^NSEI": "India",
    }

    def to_month_end(d):
        return pd.to_datetime(d).to_period("M").to_timestamp("M")

    def fetch_country_iso_map():
        url = "https://api.worldbank.org/v2/country?format=json&per_page=400"
        rows = requests.get(url, timeout=30).json()[1]
        return {r["name"]: r["iso2Code"] for r in rows if r["iso2Code"]}

    COUNTRY_ISO = fetch_country_iso_map()

    def resolve_country(t):
        info = yf.Ticker(t).info
        return info.get("country") or INDEX_COUNTRY_MAP.get(t)

    def fetch_macro_country(iso2):
        frames = []
        for name, code in WB_INDICATORS.items():
            url = f"https://api.worldbank.org/v2/country/{iso2}/indicator/{code}?format=json&per_page=2000"
            data = requests.get(url, timeout=30).json()
            if not data or data[1] is None:
                return None
            df = pd.DataFrame(data[1])[["date", "value"]].dropna()
            df["date"] = pd.to_datetime(df["date"] + "-12-31").apply(to_month_end)
            df.rename(columns={"value": name}, inplace=True)
            frames.append(df)

        m = frames[0]
        for f in frames[1:]:
            m = m.merge(f, on="date", how="outer")

        return m.sort_values("date").interpolate().ffill()

    # ----------------------------
    # Inference
    # ----------------------------
    country = resolve_country(ticker)
    if not country or country not in COUNTRY_ISO:
        return {
            "prediction": [0.33, 0.33, 0.34],
            "confidence": 0.2,
            "reason": "Macroeconomic data unavailable for this region.",
            "model": "Macro"
        }

    macro = fetch_macro_country(COUNTRY_ISO[country])
    if macro is None:
        return {
            "prediction": [0.33, 0.33, 0.34],
            "confidence": 0.2,
            "reason": "Insufficient macroeconomic indicators.",
            "model": "Macro"
        }

    last = macro.iloc[-1]
    X = pd.DataFrame([last[FEATURES]])
    Xs = scaler.transform(X)

    p_buy = float(model.predict_proba(Xs)[0, 1])
    p_sell = 1 - p_buy
    p_hold = 1 - abs(p_buy - 0.5) * 2

    confidence = round(max(p_buy, p_sell), 2)

    reason = (
        "Supportive macro conditions (GDP growth, inflation, employment)"
        if p_buy > 0.55
        else "Macroeconomic headwinds detected"
        if p_sell > 0.55
        else "Neutral macroeconomic environment"
    )

    output = {
        "prediction": [round(p_buy, 2), round(p_sell, 2), round(p_hold, 2)],
        "confidence": confidence,
        "reason": reason,
        "model": "Macro"
    }

    # 👇 ADD THIS LINE TO SEE THE RESULT
    print(f"📊 Macro Output: {output}")

    return output

